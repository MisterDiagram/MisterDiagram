#[test]
fn nested_groups_mix_reflections_without_mirroring_or_moving_the_block() {
    for (i, (cells, native)) in NESTED.iter().enumerate() {
        let mut nodes = Vec::new();
        for (id, values) in cells.iter().enumerate() {
            let mut s = skeleton::rectangle(id as u32 + 1, 0., 0., 1., 1., if id == 2 { "FROG" } else { "" }).unwrap();
            for (name, value) in NAMES.iter().zip(values) {
                set(&mut s, name, *value);
            }
            if id < 2 {
                s.shape_type = Some("Group".into());
                s.sheet.sections.clear();
                set(&mut s, "DisplayMode", 1.);
            }
            nodes.push(s);
        }
        let child = nodes.pop().unwrap();
        let mut inner = nodes.pop().unwrap();
        inner.shapes.push(child);
        let mut outer = nodes.pop().unwrap();
        outer.shapes.push(inner);
        let mut d = skeleton::document(false);
        d.pages[0].shapes = vec![outer].into();
        let scene = scene::page(&d, 0, scene::Options { crop: false, scale: 2., ..Default::default() }).unwrap();
        let transform = scene.ops.iter().find_map(|o| if let Op::Text { transform, .. } = o { Some(*transform) } else { None }).unwrap();
        let page = Affine::new([72., 0., 0., -72., 0., 504.]) * transform;
        for (actual, expected) in page.as_coeffs()[..4].iter().zip(&native[..4]) {
            assert!((actual - expected).abs() < 1e-5, "nested {i}: {actual} != {expected}");
        }
        let center = page * Point::new(46.8, 21.6);
        assert!((center.x - native[4]).abs() <= 0.375 && (center.y - native[5]).abs() <= 0.375, "nested {i}: {center:?} != {:?}", &native[4..]);
    }
}
