#[test]
fn expanded_text_and_background_follow_nested_reflections_and_drawing_scale() {
    use misterdiagram_model::{Row, Section};
    for (i, (cells, baseline, background)) in EXPANDED.iter().enumerate() {
        let mut nodes = Vec::new();
        for (id, values) in cells.iter().enumerate() {
            let mut s = skeleton::rectangle(id as u32 + 1, 0., 0., 1., 1., if id == 2 { "FROG\nFROG\nFROG" } else { "" }).unwrap();
            for (name, value) in NAMES.iter().zip(values) {
                set(&mut s, name, *value);
            }
            if id < 2 {
                s.shape_type = Some("Group".into());
                s.sheet.sections.clear();
                set(&mut s, "DisplayMode", 1.);
            } else {
                for n in ["LeftMargin", "RightMargin", "TopMargin", "BottomMargin"] {
                    set(&mut s, n, 0.);
                }
                set(&mut s, "VerticalAlign", (i % 3) as f64);
                set(&mut s, "TextBkgnd", 5.);
                for (name, cells) in
                    [("Character", vec![("Font", "99"), ("Size", "0.25")]), ("Paragraph", vec![("HorzAlign", "1"), ("SpLine", "-1.2")])]
                {
                    s.sheet.sections.push(Section {
                        name: name.into(),
                        rows: vec![Row {
                            index: Some(0),
                            cells: cells.into_iter().map(|(n, v)| Cell { name: n.into(), value: Some(v.into()), ..Default::default() }).collect(),
                            ..Default::default()
                        }],
                        ..Default::default()
                    });
                }
            }
            nodes.push(s);
        }
        let child = nodes.pop().unwrap();
        let mut inner = nodes.pop().unwrap();
        inner.shapes.push(child);
        let mut outer = nodes.pop().unwrap();
        outer.shapes.push(inner);
        let mut d = skeleton::document(false);
        d.face_names.insert(99, "Calibri".into());
        d.pages[0].shapes = vec![outer].into();
        for (n, v) in [("PageWidth", 7.), ("PageHeight", 7.), ("PageScale", 1.), ("DrawingScale", if i == 3 { 2. } else { 1. })] {
            d.pages[0].sheet.cells.retain(|c| c.name != n);
            d.pages[0].sheet.cells.push(Cell { name: n.into(), value: Some(v.to_string()), ..Default::default() });
        }
        let scene = scene::page(&d, 0, scene::Options { crop: false, scale: 2., ..Default::default() }).unwrap();
        let (layout, transform) =
            scene.ops.iter().find_map(|op| if let Op::Text { layout, transform, .. } = op { Some((layout, *transform)) } else { None }).unwrap();
        let (_, x, y) = layout.runs[0].glyphs[0];
        let view = Affine::new([72., 0., 0., -72., 0., scene.page_size.1 * 72.]);
        let actual = view * transform * Point::new(x, y);
        assert!(
            (actual.x - baseline[0]).abs() <= 0.375 && (actual.y - baseline[1]).abs() <= 0.375,
            "expanded {i}: baseline {actual:?} != {baseline:?}"
        );
        let (rect, bg_transform) = scene
            .ops
            .iter()
            .find_map(|op| if let Op::TextBackground { rect, transform, .. } = op { Some((*rect, *transform)) } else { None })
            .unwrap();
        assert_eq!(transform, bg_transform);
        let rect = (view * bg_transform).transform_rect_bbox(rect);
        for (a, b) in [rect.x0, rect.y0, rect.x1, rect.y1].iter().zip(background) {
            assert!((a - b).abs() <= 0.375, "expanded {i}: background {rect:?} != {background:?}");
        }
    }
}
