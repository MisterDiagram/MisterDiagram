use misterdiagram_geom::{Affine, Point};
use misterdiagram_model::{Cell, Shape, skeleton};
use misterdiagram_render::scene::{self, Op};

fn set(s: &mut Shape, name: &str, value: f64) {
    s.sheet.cells.retain(|c| c.name != name);
    s.sheet.cells.push(Cell { name: name.into(), value: Some(value.to_string()), ..Default::default() });
}
fn formula(s: &mut Shape, name: &str, value: &str) {
    s.sheet.cells.retain(|c| c.name != name);
    s.sheet.cells.push(Cell { name: name.into(), formula: Some(value.into()), ..Default::default() });
}
fn text(s: &mut Shape, kind: usize) {
    s.text = skeleton::rectangle(99, 0., 0., 1., 1., "FROG").unwrap().text;
    for (n, v) in [
        ("TxtWidth", 1.3),
        ("TxtHeight", 0.6),
        ("TxtPinX", 1.6),
        ("TxtPinY", 0.85),
        ("TxtLocPinX", 0.4),
        ("TxtLocPinY", 0.2),
        ("LeftMargin", 0.),
        ("RightMargin", 0.),
        ("TopMargin", 0.),
        ("BottomMargin", 0.),
    ] {
        set(s, n, v);
    }
    match kind {
        1 => set(s, "TxtAngle", std::f64::consts::PI / 6.),
        2 => formula(s, "TxtAngle", "GRAVITY(Angle,110 deg,-70 deg)"),
        _ => set(s, "TxtAngle", 0.),
    }
}

#[test]
fn off_centre_leaf_group_and_child_match_native_transform_matrix() {
    let mut index = 0;
    for kind in 0..3 {
        for angle in [0_f64, 90., 180.] {
            for txt in 0..3 {
                for (fx, fy) in [(0., 0.), (1., 0.), (0., 1.), (1., 1.)] {
                    let mut root = skeleton::rectangle(1, 2., 2.5, 2., 1., "").unwrap();
                    if kind == 0 {
                        text(&mut root, txt);
                    } else {
                        root.shape_type = Some("Group".into());
                        root.sheet.sections.clear();
                        let mut child = skeleton::rectangle(2, 0., 0., 2., 1., "").unwrap();
                        if kind == 1 {
                            text(&mut root, txt);
                        } else {
                            text(&mut child, txt);
                        }
                        root.shapes.push(child);
                        set(&mut root, "DisplayMode", 1.);
                    }
                    for (n, v) in
                        [("PinX", 3.), ("PinY", 3.), ("LocPinX", 0.65), ("LocPinY", 0.3), ("Angle", angle.to_radians()), ("FlipX", fx), ("FlipY", fy)]
                    {
                        set(&mut root, n, v);
                    }
                    let mut d = skeleton::document(false);
                    d.pages[0].shapes = vec![root].into();
                    let scene = scene::page(&d, 0, scene::Options { crop: false, scale: 2., ..Default::default() }).unwrap();
                    let transforms: Vec<_> =
                        scene.ops.iter().filter_map(|o| if let Op::Text { transform, .. } = o { Some(*transform) } else { None }).collect();
                    assert_eq!(transforms.len(), 1);
                    let page = Affine::new([72., 0., 0., -72., 0., 432.]) * transforms[0];
                    let native = NATIVE[index];
                    for (actual, expected) in page.as_coeffs()[..4].iter().zip(&native[..4]) {
                        assert!((actual - expected).abs() < 1e-5, "case {index}: orientation {actual} != {expected}");
                    }
                    let center = page * Point::new(46.8, 21.6);
                    assert!(
                        (center.x - native[4]).abs() <= 0.375 && (center.y - native[5]).abs() <= 0.375,
                        "case {index}: block center {center:?} != {:?}",
                        &native[4..]
                    );
                    index += 1;
                }
            }
        }
    }
    assert_eq!(index, NATIVE.len());
}

