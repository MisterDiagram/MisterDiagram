//! Numeric language identifiers for the documented VSDX culture names.
use crate::Error;
/// Convert the normative vLanguageString table to the corresponding LCID.
/// https://learn.microsoft.com/en-us/openspecs/sharepoint_protocols/ms-vsdx/f91b1356-cff1-4c71-8a04-247007cbe4c9
/// https://learn.microsoft.com/en-us/office/client-developer/visio/language-function
pub fn lcid(value: &str) -> Result<u16, Error> {
    if value.len() > 128 {
        return Err(Error::Limit);
    }
    if let Ok(id) = value.parse::<u16>() {
        return Ok(id);
    }
    LANGUAGES
        .iter()
        .find_map(|(name, id)| name.eq_ignore_ascii_case(value).then_some(*id))
        .ok_or_else(|| Error::Unsupported(format!("language {value}")))
}
