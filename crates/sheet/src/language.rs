#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn microsoft_language_examples_and_hostile_input() {
        assert_eq!(lcid("en-us"), Ok(1033));
        assert_eq!(lcid("es-es"), Ok(3082));
        assert_eq!(lcid("1033"), Ok(1033));
        assert!(lcid("not-a-language").is_err());
        assert_eq!(lcid(&"x".repeat(129)), Err(Error::Limit));
        for (name, id) in LANGUAGES {
            assert_eq!(lcid(name), Ok(*id));
        }
    }
}
