//! Deterministic inventory of URLs cited by Rust doc comments and oracle scripts.
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io::Read;
use std::path::Path;

const MAX_SOURCE: usize = 16 * 1024 * 1024;
type Citations = BTreeMap<String, BTreeSet<String>>;

fn urls(text: &str) -> Result<BTreeSet<String>, String> {
    if text.len() > MAX_SOURCE {
        return Err("source exceeds size cap".into());
    }
    let mut found = BTreeSet::new();
    for token in text.split(|c: char| c.is_whitespace() || matches!(c, '"' | '\'' | '`' | '<' | '>' | '[' | ']' | '{' | '}')) {
        let mut rest = token;
        while let Some(marker) = rest.find("://") {
            let before = rest.get(..marker).ok_or("invalid URL boundary")?;
            let start = before
                .char_indices()
                .rfind(|(_, c)| !c.is_ascii_alphanumeric() && !matches!(c, '+' | '-' | '.'))
                .map_or(0, |(i, c)| i + c.len_utf8());
            let scheme = before.get(start..).ok_or("invalid URL scheme")?;
            let after = rest.get(marker + 3..).ok_or("invalid URL separator")?;
            if !scheme.is_empty() && scheme.starts_with(|c: char| c.is_ascii_alphabetic()) {
                let mut tail = after.trim_end_matches(['.', ',', ';', ':']);
                while tail.ends_with(')') && tail.matches(')').count() > tail.matches('(').count() {
                    tail = tail.strip_suffix(')').ok_or("invalid URL end")?;
                }
                if !tail.is_empty() {
                    if tail.len() > 8192 {
                        return Err("URL exceeds length cap".into());
                    }
                    found.insert(format!("{scheme}://{tail}"));
                }
            }
            rest = after;
        }
    }
    Ok(found)
}

fn doc_text(source: &str) -> String {
    let mut text = String::new();
    let mut block = false;
    for line in source.lines() {
        let line = line.trim_start();
        if (line.starts_with("///") && !line.starts_with("////")) || line.starts_with("//!") {
            text.push_str(line);
            text.push('\n');
        } else if block || line.starts_with("/**") || line.starts_with("/*!") {
            let content = line.split_once("*/").map_or(line, |(before, _)| before);
            text.push_str(content);
            text.push('\n');
            block = !line.contains("*/");
        }
    }
    text
}

fn walk(root: &Path, path: &Path, depth: usize, visited: &mut usize, result: &mut Citations) -> Result<(), String> {
    *visited = visited.checked_add(1).ok_or("source count overflow")?;
    if depth > 16 || *visited > 20000 {
        return Err("source traversal exceeds cap".into());
    }
    let meta = fs::symlink_metadata(path).map_err(|e| e.to_string())?;
    if meta.file_type().is_symlink() {
        return Err(format!("source symlink: {}", path.display()));
    }
    if meta.is_dir() {
        for item in fs::read_dir(path).map_err(|e| e.to_string())? {
            walk(root, &item.map_err(|e| e.to_string())?.path(), depth + 1, visited, result)?;
        }
        return Ok(());
    }
    let ext = path.extension().and_then(|s| s.to_str()).unwrap_or_default();
    let oracle = path.starts_with(root.join("tools/oracle")) && matches!(ext, "ps1" | "sh" | "py");
    if ext != "rs" && !oracle {
        return Ok(());
    }
    let mut source = String::new();
    fs::File::open(path).map_err(|e| e.to_string())?.take(MAX_SOURCE as u64 + 1).read_to_string(&mut source).map_err(|e| e.to_string())?;
    if source.len() > MAX_SOURCE {
        return Err("source exceeds size cap".into());
    }
    let text = if oracle { source } else { doc_text(&source) };
    let name = path.strip_prefix(root).map_err(|e| e.to_string())?.to_str().ok_or("non-UTF-8 source path")?.replace('\\', "/");
    for url in urls(&text)? {
        result.entry(url).or_default().insert(name.clone());
    }
    if result.len() > 10000 || result.values().map(BTreeSet::len).sum::<usize>() > 100000 {
        return Err("source citation count exceeds cap".into());
    }
    Ok(())
}

fn render(citations: &Citations) -> String {
    let mut text = String::from(
        "# Source references\n\nGenerated by `cargo xtask sources` from Rust doc comments and tools/oracle scripts.\nCI rejects a stale inventory. Inclusion records a citation, not an endorsement or a claim\nthat the page was consulted during this session.\n\n| URL | Citing files |\n|---|---|\n",
    );
    for (url, files) in citations {
        let escaped = url.replace('|', "%7C");
        let files = files.iter().map(|name| format!("`{name}`")).collect::<Vec<_>>().join(", ");
        text.push_str(&format!("| <{escaped}> | {files} |\n"));
    }
    text
}

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let mut citations = Citations::new();
    let mut visited = 0;
    for area in ["crates", "apps", "xtask", "tools/oracle"] {
        walk(root, &root.join(area), 0, &mut visited, &mut citations)?;
    }
    let expected = render(&citations);
    let path = root.join("docs/sources.md");
    if check {
        let actual = fs::read_to_string(&path).map_err(|e| format!("sources inventory missing: {e}; run cargo xtask sources"))?;
        if actual != expected {
            return Err("docs/sources.md is stale; run cargo xtask sources".into());
        }
    } else {
        fs::write(&path, expected).map_err(|e| e.to_string())?;
    }
    println!("Sources: {} sorted, deduplicated URLs with citing files{}.", citations.len(), if check { " verified" } else { " generated" });
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn doc_comments_and_all_oracle_urls_are_collected() {
        let source = "// https://ignored.invalid\n/// [page](https://learn.microsoft.com/a).\n//! <http://example.org/b>\n/** https://example.org/c\n * ftp://example.org/d */\n";
        let found = urls(&doc_text(source)).unwrap();
        assert_eq!(found.len(), 4);
        assert!(found.contains("https://learn.microsoft.com/a"));
        assert!(!found.contains("https://ignored.invalid"));
        assert_eq!(urls("https://example.org/x https://example.org/x").unwrap().len(), 1);
        assert!(urls(&"x".repeat(MAX_SOURCE + 1)).is_err());
        assert!(urls(&format!("https://{}", "x".repeat(8193))).is_err());
        assert!(urls("雪 :// () \0").unwrap().is_empty());
        assert!(urls("🔗https://example.org/a_(b)).").unwrap().contains("https://example.org/a_(b)"));
    }
    #[test]
    fn inventory_is_sorted_and_stale_files_fail() -> Result<(), String> {
        let root = crate::root().join("target").join(format!("sources-test-{}", std::process::id()));
        for area in ["crates", "apps", "xtask", "tools/oracle", "docs"] {
            fs::create_dir_all(root.join(area)).map_err(|e| e.to_string())?;
        }
        fs::write(root.join("crates/example.rs"), "/// https://example.org/z\n/// https://example.org/a\n").map_err(|e| e.to_string())?;
        run(&root, false)?;
        run(&root, true)?;
        let text = fs::read_to_string(root.join("docs/sources.md")).map_err(|e| e.to_string())?;
        assert!(text.find("https://example.org/a") < text.find("https://example.org/z"));
        fs::write(root.join("crates/example.rs"), "/// https://example.org/new\n").map_err(|e| e.to_string())?;
        assert!(run(&root, true).is_err());
        fs::remove_dir_all(root).map_err(|e| e.to_string())?;
        Ok(())
    }
}
