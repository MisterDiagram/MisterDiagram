#!/usr/bin/env python3
"""Generate scoped default facts from the brief-authorized blank-document observations.

This never changes the observations. Authored rectangle size, position and geometry are
excluded. Sources and their digests are recorded in the generated Rust module.
"""
import csv
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIMIT = 2 * 1024 * 1024
HEADER = ['shape_id', 'shape_name', 'section', 'row', 'cell', 'name', 'formula', 'result_iu', 'units']

def rows(path):
    with path.open("rb") as stream:
        data = stream.read(LIMIT + 1)
    if len(data) > LIMIT:
        raise ValueError('default TSV exceeds size cap')
    reader = csv.DictReader(io.StringIO(data.decode('utf-8-sig')), delimiter='\t')
    if reader.fieldnames != HEADER:
        raise ValueError('default TSV header mismatch')
    result = []
    seen = set()
    for row in reader:
        if None in row or any(v is None or len(v) > 65536 for v in row.values()):
            raise ValueError('invalid default TSV row')
        if row['name'] in seen or len(result) >= 4096:
            raise ValueError('duplicate default name or row cap')
        seen.add(row['name'])
        for field in ('section', 'row', 'cell', 'units'):
            n = int(row[field])
            if not 0 <= n <= 32767:
                raise ValueError('invalid default coordinate')
        result.append(row)
    return result, hashlib.sha256(data).hexdigest()

def generate():
    out = ['//! Scoped baseline defaults observed in the authorized blank Visio document.',
           '//! Generated by tools/generate-defaults.py; never use specimen geometry as defaults.',
           'use super::{Cell, Scope};', 'use std::{collections::BTreeMap, sync::LazyLock};',
           '#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]',
           'pub(super) enum Kind { Document, Page, Shape, Style }',
           'pub(super) struct DefaultCell { pub kind: Kind, pub cell: Cell }',
           '/// Blank baseline fallback after actual document/master/style values.',
           '/// https://learn.microsoft.com/en-us/office/client-developer/visio/cell-elementvisio-xml',
           '/// https://learn.microsoft.com/en-us/openspecs/sharepoint_protocols/ms-vsdx/59214758-549c-4f99-a4de-de2bf5fb08d3',
           'pub(super) static CELLS: LazyLock<Vec<DefaultCell>> = LazyLock::new(|| RAW.iter().map(|(kind,name,value,formula,string,src)| DefaultCell {kind:*kind,cell:Cell {name:(*name).into(),value:Some((*value).into()),formula:formula.map(str::to_owned),units:string.then(||"STR".into()),attributes:BTreeMap::from([("ComSection".into(),src.0.to_string()),("ComRow".into(),src.1.to_string()),("ComCell".into(),src.2.to_string()),("ComUnits".into(),src.3.to_string())]),..Default::default()}}).collect());',
           'type RawDefault = (Kind, &\'static str, &\'static str, Option<&\'static str>, bool, (u16,u16,u16,u16));',
           '#[rustfmt::skip]', 'const RAW: &[RawDefault] = &[']
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    for kind, name in [('Document','document.tsv'),('Page','page.tsv'),('Style','style-0-No_Style.tsv'),('Shape','rectangle.tsv')]:
        records, digest = rows(ROOT/'corpus/blank'/name)
        out.append(f'// Source corpus/blank/{name}, SHA256 {digest}.')
        for r in records:
            if kind == 'Shape' and (r['section'] == '10' or r['name'] in {'PinX','PinY','Width','Height'}):
                continue
            f = r['formula']
            v = r['result_iu']
            # String results are represented by their literal contents; ResultIU is numeric only.
            string = f.startswith('"') and f.endswith('"')
            if string:
                v = f[1:-1].replace('""','"')
            coords = ','.join(r[k] for k in ['section','row','cell','units'])
            out.append('(Kind::'+kind+','+quote(r['name'])+','+quote(v)+','+('Some('+quote(f)+')' if f else 'None')+','+str(string).lower()+',('+coords+')),')
    out += ['];', 'pub(super) fn kind(scope: Scope) -> Kind { match scope { Scope::Document=>Kind::Document, Scope::Page(_)|Scope::Master(_)=>Kind::Page, Scope::Style(_)=>Kind::Style, _=>Kind::Shape } }']
    out += ['static INDEX: LazyLock<BTreeMap<(Kind,String),usize>> = LazyLock::new(|| CELLS.iter().enumerate().map(|(i,c)|((c.kind,c.cell.name.to_ascii_lowercase()),i)).collect());',
            'pub(super) fn cell(scope: Scope, name: &str) -> Option<&\'static Cell> { let index = INDEX.get(&(kind(scope),name.to_ascii_lowercase()))?; CELLS.get(*index).map(|c|&c.cell) }']
    (ROOT/'crates/vsdx/src/evaluate/defaults.rs').write_text('\n'.join(out)+'\n')
if __name__ == '__main__':
    generate()
